"""Generate paper/ml_numbers.tex (macros) and paper/ml_table.tex (results table) for the Meet-LWE section.

Best point per key w{omega}_d{d}_{p|f} over cloud/results/*/res, runs/hop_*.npy and points/ is copied to
points/w{omega}_d{d}_{p|f}.npy (kept in git).  Every T is re-evaluated with the independent ml_recost.cost and must
agree with meetlwe_model to 1e-6 (else the script stops).  May's published values are his Table 5 (ePrint 2021/216);
the re-optimised column is parsed from runs/may_rep1_depth.log (may_rep1.py, his formulas, May depths 4-6 = our d 3-5).
usage: python3 ntru_hybrid/make_ml_numbers.py
"""
import sys, os, glob, re, shutil
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import numpy as np
from meetlwe_model import TModel
from ml_worker import T_of
from ml_recost import cost

OMS = ["0.3", "0.375", "0.441", "0.5", "0.62", "0.667"]; LET = "ABCDEF"
MAY_PUB = {"0.3": 0.298, "0.375": 0.323, "0.441": 0.340, "0.5": 0.356, "0.62": 0.389, "0.667": 0.407}
DEPTHS = range(3, 8); PTS = os.path.join(HERE, "points"); PAPER = os.path.join(ROOT, "paper")
os.makedirs(PTS, exist_ok=True)


def cands(k):
    fs = glob.glob(os.path.join(ROOT, "cloud", "results", "*", "res", k + "_T*.npy")) + [os.path.join(PTS, k + ".npy")]
    om, d, fl = k[1:].split("_"); fs.append(os.path.join(HERE, "runs", f"hop_w{om}_{d}_{fl}.npy"))
    return [f for f in fs if os.path.exists(f)]


def best(om, d, filt):
    k = f"w{om}_d{d}_{'f' if filt else 'p'}"; M = TModel([-1, 0, 1], float(om)); b = (9.0, None, None)
    for f in cands(k):
        z = np.load(f); Tr = cost(z, [-1, 0, 1], d, float(om), filt)[0]
        if Tr < b[0] - 1e-9:
            Tm = T_of(M, z, d, filt)
            if abs(Tm - Tr) > 1e-6:
                sys.exit(f"MISMATCH {f}: model {Tm} recost {Tr}")
            b = (Tr, z, f)
    if b[1] is not None and b[2] != os.path.join(PTS, k + ".npy"):
        np.save(os.path.join(PTS, k + ".npy"), b[1])
    return b[0]


def first_depth(Ts):                       # smallest depth within 1e-5 of the best (deeper copies tie exactly)
    m = min(Ts.values()); return m, min(d for d, T in Ts.items() if T < m + 1e-5)


may_re, may4 = {}, {}
for line in open(os.path.join(HERE, "runs", "may_rep1_depth.log")):
    m = re.match(r"omega ([\d.]+): May depth (\d): T = ([\d.]+)", line)
    if m:
        may_re[m.group(1)] = min(may_re.get(m.group(1), 9.0), float(m.group(3)))
        if m.group(2) == "4":
            may4[m.group(1)] = float(m.group(3))

mac, rows, gains, fds, g3, deep = [], [], {}, [], [], []
for om, L in zip(OMS, LET):
    Pd = {d: best(om, d, False) for d in DEPTHS}; Fd = {d: best(om, d, True) for d in DEPTHS}
    Tp, dp = first_depth(Pd); Tf, df = first_depth(Fd)
    g = Tp - Tf; gains[om] = g; fds.append(df); g3.append(Pd[3] - Fd[3]); deep.append(Fd[4] - Tf)
    mac += [f"\\newcommand{{\\MLpub{L}}}{{{MAY_PUB[om]:.3f}}}", f"\\newcommand{{\\MLre{L}}}{{{may_re[om]:.4f}}}",
            f"\\newcommand{{\\MLfour{L}}}{{{may4[om]:.4f}}}",
            f"\\newcommand{{\\MLp{L}}}{{{Tp:.4f}}}", f"\\newcommand{{\\MLpd{L}}}{{{dp}}}",
            f"\\newcommand{{\\MLf{L}}}{{{Tf:.4f}}}", f"\\newcommand{{\\MLfd{L}}}{{{df}}}",
            f"\\newcommand{{\\MLg{L}}}{{{g:.4f}}}"]
    rows.append(f"${om}$ & ${MAY_PUB[om]:.3f}$ & ${may_re[om]:.4f}$ & ${Pd[3]:.4f}$ / ${Fd[3]:.4f}$ & ${Pd[4]:.4f}$ / ${Fd[4]:.4f}$"
                f" & ${Tp:.4f}$ ({dp}) & ${Tf:.4f}$ ({df}) & ${g:.4f}$ \\\\")
hi = [gains[o] for o in OMS if float(o) >= 0.375]
B = os.path.join(HERE, "runs", "bias_sim_meetlwe2.log")         # filter bias simulation (check 4)
for line in (open(B) if os.path.exists(B) else []):
    m = re.match(r"filter (on|off).*mean sigma ([\d.]+)\s+planted survival ([\d.]+) \+- ([\d.]+)", line)
    if m:
        t = "On" if m.group(1) == "on" else "Off"
        mac += [f"\\newcommand{{\\MLbias{t}}}{{{float(m.group(3)):.3f}\\pm{float(m.group(4)):.3f}}}",
                f"\\newcommand{{\\MLbias{t}Sig}}{{{float(m.group(2)):.3f}}}"]
for fx in glob.glob(os.path.join(HERE, "runs", "ml_fixed_law_w*_d*.log")):     # filters at fixed split laws
    for line in open(fx):
        m = re.match(r"omega ([\d.]+) d (\d+): .*fixed split laws ([\d.]+)", line)
        if m:
            mac.append(f"\\newcommand{{\\MLfixed{LET[OMS.index(m.group(1))]}}}{{{float(m.group(3)):.4f}}}")
mac += [f"\\newcommand{{\\MLgthreemin}}{{{min(g3):.3f}}}", f"\\newcommand{{\\MLgthreemax}}{{{max(g3):.3f}}}",
        f"\\newcommand{{\\MLdeepmax}}{{{max(deep):.3f}}}"]
mac += [f"\\newcommand{{\\MLfdmin}}{{{min(fds)}}}", f"\\newcommand{{\\MLfdmax}}{{{max(fds)}}}"]
mac += [f"\\newcommand{{\\MLgainmin}}{{{min(hi):.3f}}}", f"\\newcommand{{\\MLgainmax}}{{{max(hi):.3f}}}"]
open(os.path.join(PAPER, "ml_numbers.tex"), "w").write("% generated by ntru_hybrid/make_ml_numbers.py\n" + "\n".join(mac) + "\n")
open(os.path.join(PAPER, "ml_table.tex"), "w").write(
    "% generated by ntru_hybrid/make_ml_numbers.py\n\\begin{tabular}{llllllll}\n\\toprule\n"
    " & & & \\multicolumn{2}{l}{unfiltered / filtered} & \\multicolumn{2}{l}{best over $d\\le7$} & \\\\\n"
    "$\\omega$ & May~\\cite{May21} & May, re-opt. & $d=3$ & $d=4$ & unfiltered ($d$) & filtered ($d$) & gain \\\\\n\\midrule\n"
    + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
print("\n".join(rows))
